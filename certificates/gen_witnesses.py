#!/usr/bin/env python3
"""Emit the 190 per-radicand witness instances as kernel-checked Lean facts.

Input : witnesses.json next to this script (COMPUTED by witnesses.py; the least split prime p per
        fundamental -d).
Output: <out>/Witnesses/Chunk<k>.lean (<= CHUNK theorems each) and <out>/Witnesses.lean (the
        aggregate: nonHeegner190, exists_witness, the range lemma, and the assembled
        classNumber_ne_one theorem), where <out> is the first argument, by default
        ../formalization/CN1/Finite.

Every emitted fact is `CN1.Finite.IsWitness m p y` (SplitPrime.lean): p prime, p | y^2 - t y + c,
4p <= d, p != c, with (t, c, d) = (tOf m, cOf m, dOf m). The proofs are `norm_num` (primality)
and `decide` (the rest); no native_decide anywhere. The script recomputes everything from m and
treats the p from witnesses.json as untrusted input: a wrong p would simply fail the checks below
and the Lean kernel would reject the instance anyway.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WITNESSES = os.path.join(HERE, "witnesses.json")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "formalization", "CN1", "Finite")
CHUNK = 50
NINE = [1, 2, 3, 7, 11, 19, 43, 67, 163]
DMAX = 652


def is_prime(n):
    if n < 2:
        return False
    k = 2
    while k * k <= n:
        if n % k == 0:
            return False
        k += 1
    return True


def squarefree(n):
    k = 2
    while k * k <= n:
        if n % (k * k) == 0:
            return False
        k += 1
    return True


def tcd(m):
    if m % 4 == 3:
        return 1, (m + 1) // 4, m
    return 0, m, 4 * m


def main():
    rows = json.load(open(WITNESSES))["rows"]
    wit = {}
    for r in rows:
        if r["witness"] is None:
            continue
        m, p, d = r["m"], r["witness"], r["d"]
        t, c, dd = tcd(m)
        assert dd == d, (m, d, dd)
        assert is_prime(p), (m, p)
        assert 4 * p <= d, (m, p, d)
        assert p != c, (m, p, c)
        assert d % p != 0, ("not split", m, p)
        ys = [y for y in range(1, p + 1) if (y * y - t * y + c) % p == 0]
        assert ys, ("no root mod p", m, p)
        y = ys[0]
        assert t * y <= y * y + c
        assert (y * y + c - t * y) % p == 0
        wit[m] = (p, y)

    # Independent recomputation of the domain: squarefree m with dOf m <= 652, m not in NINE.
    dom = sorted(m for m in range(1, DMAX + 1) if squarefree(m) and tcd(m)[2] <= DMAX and m not in NINE)
    assert len(dom) == 190, len(dom)
    assert dom == sorted(wit), "witnesses.json set differs from the recomputed domain"

    ms = dom
    chunks = [ms[i:i + CHUNK] for i in range(0, len(ms), CHUNK)]
    os.makedirs(os.path.join(OUT, "Witnesses"), exist_ok=True)
    for k, ch in enumerate(chunks, 1):
        lines = ["import CN1.Finite.SplitPrime", "",
                 f"/-! CN1.Finite.Witnesses.Chunk{k}: witness instances {ch[0]} <= m <= {ch[-1]}",
                 "(generated by certificates/gen_witnesses.py from certificates/witnesses.json; do not edit). -/",
                 "", "namespace CN1.Finite", ""]
        for m in ch:
            p, y = wit[m]
            t, c, d = tcd(m)
            lines.append(f"/-- m = {m}, d = {d}, t = {t}, c = {c}: p = {p}, y = {y}. -/")
            lines.append(f"theorem w_{m} : IsWitness {m} {p} {y} :=")
            lines.append("  ⟨by norm_num, by decide, by decide, by decide, by decide⟩")
            lines.append("")
        lines.append(f"/-- The radicands of this chunk. -/")
        lines.append(f"def chunk{k} : List ℕ := [{', '.join(str(m) for m in ch)}]")
        lines.append("")
        lines.append("set_option maxRecDepth 4096 in")
        lines.append(f"theorem exists_witness_chunk{k} : ∀ m ∈ chunk{k}, ∃ p y : ℕ, IsWitness m p y := by")
        lines.append("  intro m hm")
        lines.append(f"  simp only [chunk{k}, List.mem_cons, List.mem_nil_iff, or_false] at hm")
        lines.append("  rcases hm with " + " | ".join(["rfl"] * len(ch)))
        lines.append("  exacts [" + ", ".join(f"⟨_, _, w_{m}⟩" for m in ch) + "]")
        lines.append("")
        lines += ["end CN1.Finite", ""]
        open(os.path.join(OUT, "Witnesses", f"Chunk{k}.lean"), "w").write("\n".join(lines))

    # Aggregate file.
    L = ["import Mathlib"]
    L += [f"import CN1.Finite.Witnesses.Chunk{k}" for k in range(1, len(chunks) + 1)]
    L += ["", "/-!",
          "# CN1.Finite.Witnesses: the finite search, assembled",
          "",
          "Generated by certificates/gen_witnesses.py (do not edit). `nonHeegner190` is the set of",
          "squarefree radicands `m` with `dOf m ≤ 652` outside the nine; `exists_witness_of_mem` collects",
          "the 190 per-`m` instances; `mem_nonHeegner190` is the kernel-checked range lemma; and",
          "`classNumber_ne_one_of_quadInt` is the assembled finite part, conditional on the algebraic data `QuadInt`.",
          "-/", "", "open NumberField", "", "namespace CN1.Finite", ""]
    L.append("/-- The 190 squarefree radicands `m` with `|disc ℚ(√-m)| ≤ 652` and `h ≠ 1`. -/")
    L.append("def nonHeegner190 : List ℕ := " + " ++ ".join(f"chunk{k}" for k in range(1, len(chunks) + 1)))
    L.append("")
    L.append("theorem length_nonHeegner190 : nonHeegner190.length = 190 := by decide +kernel")
    L.append("")
    L.append("theorem exists_witness_of_mem : ∀ m ∈ nonHeegner190, ∃ p y : ℕ, IsWitness m p y := by")
    L.append("  unfold nonHeegner190")
    term = "exists_witness_chunk1"
    for k in range(2, len(chunks) + 1):
        term = f"List.forall_mem_append.mpr ⟨{term}, exists_witness_chunk{k}⟩"
    L.append(f"  exact {term}")
    L.append("")
    L.append("set_option maxRecDepth 8192 in")
    L.append("/-- Every `m ≤ 652` with no square factor `k² (2 ≤ k ≤ 26)`, `dOf m ≤ 652`, outside the nine,")
    L.append("is in `nonHeegner190`. Kernel-checked by `decide`. -/")
    L.append("theorem mem_nonHeegner190 : ∀ m ∈ Finset.range 653, SqfBelow m → dOf m ≤ 652 →")
    L.append("    m ∉ ({1, 2, 3, 7, 11, 19, 43, 67, 163} : Finset ℕ) → m ∈ nonHeegner190 := by")
    L.append("  decide +kernel")
    L.append("")
    L.append("/-- **The finite part, assembled.** For squarefree `m` with `dOf m ≤ 652` outside the nine, and")
    L.append("the algebraic data `QuadInt K (tOf m) (cOf m)` (supplied by `CN1.Finite.Bridge`), the class number is not one. -/")
    L.append("theorem classNumber_ne_one_of_quadInt {K : Type*} [Field K] [NumberField K] {m : ℕ}")
    L.append("    (D : QuadInt K (tOf m) (cOf m)) (hm : Squarefree m) (hd : dOf m ≤ 652)")
    L.append("    (hnine : m ∉ ({1, 2, 3, 7, 11, 19, 43, 67, 163} : Finset ℕ)) : classNumber K ≠ 1 := by")
    L.append("  have hrange : m ∈ Finset.range 653 := Finset.mem_range.mpr (by have := le_dOf m; omega)")
    L.append("  obtain ⟨p, y, hw⟩ :=")
    L.append("    exists_witness_of_mem m (mem_nonHeegner190 m hrange (sqfBelow_of_squarefree hm) hd hnine)")
    L.append("  exact classNumber_ne_one_of_isWitness D hw")
    L.append("")
    L.append("end CN1.Finite")
    L.append("")
    open(os.path.join(OUT, "Witnesses.lean"), "w").write("\n".join(L))
    print(f"emitted {len(ms)} instances in {len(chunks)} chunks; max p = {max(p for p, _ in wit.values())}")


if __name__ == "__main__":
    main()
