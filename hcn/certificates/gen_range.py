#!/usr/bin/env python3
"""Generates HCN/Assembly/Range.lean, the finite side's range lemma (one unsharded `decide`): every squarefree m with
dOf m <= 4777 outside the 27 is in the certificates' `hcnGe3`; and from the same sets HCN/Assembly.lean and, from the
template Main.lean.in next to this script, HCN/Main.lean.
The 27-element set is READ from HCNChallenges/ClassNumberLeTwo.lean (generated by gen_sets.py), never typed;
`hcnGe3` is READ from the certificate chunk files (generated by gen_certs.py). Before emitting, this script checks that
the guarded set equals hcnGe3 exactly, and that SqfBelow69 agrees with exact squarefreeness on [0, 4778).
Usage: python3 gen_range.py <out>   (reads and writes under <out>)"""
import re, glob, os, sys
LEAN = sys.argv[1] if len(sys.argv) > 1 else "."
ch = open(f"{LEAN}/HCNChallenges/ClassNumberLeTwo.lean").read()
lits = re.findall(r"\(\{([0-9, ]+)\} : Finset ℕ\)", ch)
assert len(lits) == 2, lits
s27_txt = lits[0]; s27 = [int(x) for x in s27_txt.split(",")]
s18 = [int(x) for x in lits[1].split(",")]
assert len(s27) == 27 and len(set(s27)) == 27 and set(s18) <= set(s27) and len(s18) == 18
hcn = []
for i in range(1, 16):
    t = open(f"{LEAN}/HCN/Finite/Certs/Chunk{i}.lean").read()
    m = re.search(rf"def chunk{i} : List ℕ := \[([0-9, ]+)\]", t)
    hcn += [int(x) for x in m.group(1).split(",")]
assert len(hcn) == 1429 and len(set(hcn)) == 1429
def dOf(m): return m if m % 4 == 3 else 4 * m
def sqf(m):
    if m == 0: return False
    k = 2
    while k * k <= m:
        if m % (k * k) == 0: return False
        k += 1
    return True
def sqf69(m): return all(m % (k * k) != 0 for k in range(2, 70))
for m in range(0, 4778):
    assert sqf69(m) == sqf(m), m                  # exact on [0, 4778): 69^2 = 4761 <= 4777 < 70^2, and m = 0 fails both
guard = [m for m in range(4778) if sqf69(m) and dOf(m) <= 4777 and m not in s27]
assert sorted(guard) == sorted(hcn), "guarded set != hcnGe3"
out = f"""import HCN.Finite.Certs

/-!
# HCN.Assembly.Range: the finite side's range lemma

GENERATED by hcn/certificates/gen_range.py (do not edit). The 27-element set is read from
HCNChallenges/ClassNumberLeTwo.lean and `hcnGe3` from the certificate chunk files; the script checks that the guarded set
below equals `hcnGe3` exactly ({len(hcn)} radicands) before emitting. The shape is CN-1's `mem_nonHeegner190` with
`N = 4778` and the surrogate `SqfBelow69` (`69² = 4761 ≤ 4777 < 70²`), so the range side is `dOf m < 4778`, the
complement of the analytic side `4778 ≤ dOf m`.
-/

set_option autoImplicit false

namespace HCN.Assembly

open CN1.Finite

/-- No square factor `k²` with `2 ≤ k ≤ 69`. -/
def SqfBelow69 (m : ℕ) : Prop := ∀ k ∈ Finset.Icc 2 69, ¬ k * k ∣ m

instance : DecidablePred SqfBelow69 := fun m =>
  inferInstanceAs (Decidable (∀ k ∈ Finset.Icc 2 69, ¬ k * k ∣ m))

theorem sqfBelow69_of_squarefree {{m : ℕ}} (hm : Squarefree m) : SqfBelow69 m := by
  intro k hk h
  have := Nat.isUnit_iff.mp (hm k h)
  rw [Finset.mem_Icc] at hk
  omega

set_option maxRecDepth 8192 in
/-- Every `m < 4778` with no square factor `k²` (`2 ≤ k ≤ 69`), `dOf m ≤ 4777`, outside the 27, is in `hcnGe3`.
Kernel-checked by `decide`. -/
theorem mem_hcnGe3_of_range : ∀ m ∈ Finset.range 4778, SqfBelow69 m → dOf m ≤ 4777 →
    m ∉ ({{{s27_txt}}} : Finset ℕ) → m ∈ HCN.Finite.Certs.hcnGe3 := by
  decide +kernel

/-- **The finite side.** For `K` of degree two containing `√-m`, `m` squarefree, `dOf m < 4778` and `m` outside
the 27: `3 ≤ classNumber K` (the certificates). -/
theorem three_le_classNumber_of_lt {{K : Type*}} [Field K] [NumberField K] (hK : Module.finrank ℚ K = 2)
    {{m : ℕ}} (hm : Squarefree m) (hsq : ∃ α : K, α ^ 2 = -(m : K)) (hlt : dOf m < 4778)
    (h27 : m ∉ ({{{s27_txt}}} : Finset ℕ)) : 3 ≤ NumberField.classNumber K := by
  have hrange : m ∈ Finset.range 4778 := Finset.mem_range.mpr (by have := le_dOf m; omega)
  exact HCN.Finite.Certs.three_le_classNumber_of_mem hK hm hsq
    (mem_hcnGe3_of_range m hrange (sqfBelow69_of_squarefree hm) (by omega) h27)

end HCN.Assembly
"""
os.makedirs(f"{LEAN}/HCN/Assembly", exist_ok=True)
open(f"{LEAN}/HCN/Assembly/Range.lean", "w").write(out)
print(f"S27 read: {s27}; S18 read: {s18}")
print(f"hcnGe3: {len(hcn)} radicands; guarded set over [0, 4778) equals hcnGe3: True; SqfBelow69 exact: True")
print(f"wrote {LEAN}/HCN/Assembly/Range.lean")

# ---- HCN/Assembly.lean (the assembly, with the two interfaces as hypotheses) ----
s9 = s27[:9]
assert s9 == [1, 2, 3, 7, 11, 19, 43, 67, 163] and sorted(s27[9:]) == sorted(s18)
s9_txt = ", ".join(map(str, s9)); s18_txt = lits[1]
asm = f"""import HCN.Assembly.LowerBound
import HCN.Assembly.Range
import HCN.Finite.ClassTwo
import CN1.Main

/-!
# HCN.Assembly: the assembly, with the two interfaces as hypotheses

GENERATED by hcn/certificates/gen_range.py (do not edit): the 27-, 18- and 9-element sets are read from
HCNChallenges/ClassNumberLeTwo.lean (itself generated by gen_sets.py), never typed by hand.

The pattern is CN-1's `CN1.Assembly.Core`: the two statements (`HCN.classNumber_le_two_iff`,
`HCN.classNumber_eq_two_iff`) with two inputs as explicit hypotheses:
* `hC : CSFacts`, the general Chowla–Selberg statements (`HCN.Statements.GeneralCS`);
* `hE : ∀ α hα, EFacts hα`, the class-partition statements for this field (`HCN.Statements.ClassPartition`).

The two ranges come from ONE `lt_or_ge (dOf m) 4778`, over CN-1's `dOf m`:
* `dOf m < 4778`: the certificates via the range lemma (`three_le_classNumber_of_lt`);
* `4778 ≤ dOf m`: the analytic side (`three_le_classNumber_of_ge`).
The converse uses CN-1's `classNumber_eq_one_iff` for the nine and the bridge-lite for the eighteen.
-/

set_option autoImplicit false

open NumberField CN1.Finite

namespace HCN.Assembly

/-- **`h ≤ 2`, from the two interfaces.** The statement (HCNChallenges/ClassNumberLeTwo.lean) with the
hypotheses `hC`, `hE`. -/
theorem classNumber_le_two_iff_of_facts (hC : CSFacts) (K : Type*) [Field K] [NumberField K]
    (hK : Module.finrank ℚ K = 2)
    (m : ℕ) (hm : Squarefree m) (hsq : ∃ α : K, α ^ 2 = -(m : K))
    (hE : ∀ (α : K) (hα : α ^ 2 = -(m : K)), EFacts hα) :
    classNumber K ≤ 2 ↔ m ∈ ({{{s27_txt}}} : Finset ℕ) := by
  constructor
  · intro h2
    by_contra h27
    have hm1 : m ≠ 1 := fun h => h27 (by simp [h])
    have hm3 : m ≠ 3 := fun h => h27 (by simp [h])
    obtain ⟨α, hα⟩ := hsq
    have h3 : 3 ≤ classNumber K := by
      rcases lt_or_ge (dOf m) 4778 with hlt | hge
      · exact three_le_classNumber_of_lt hK hm ⟨α, hα⟩ hlt h27
      · exact three_le_classNumber_of_ge hC hα hK hm hm1 hm3 (hE α hα) hge
    omega
  · intro h27
    by_cases h9 : m ∈ ({{{s9_txt}}} : Finset ℕ)
    · have := (CN1.classNumber_eq_one_iff K hK m hm hsq).mpr h9
      omega
    · have h18 : m ∈ HCN.Finite.ClassTwo.classTwo18 := by
        rw [HCN.Finite.ClassTwo.classTwo18]
        simp only [Finset.mem_insert, Finset.mem_singleton] at h27 h9 ⊢
        omega
      have := HCN.Finite.ClassTwo.classNumber_eq_two_of_mem hK hm hsq h18
      omega

/-- **`h = 2`, from the two interfaces.** -/
theorem classNumber_eq_two_iff_of_facts (hC : CSFacts) (K : Type*) [Field K] [NumberField K]
    (hK : Module.finrank ℚ K = 2)
    (m : ℕ) (hm : Squarefree m) (hsq : ∃ α : K, α ^ 2 = -(m : K))
    (hE : ∀ (α : K) (hα : α ^ 2 = -(m : K)), EFacts hα) :
    classNumber K = 2 ↔ m ∈ ({{{s18_txt}}} : Finset ℕ) := by
  constructor
  · intro h2
    have h27 := (classNumber_le_two_iff_of_facts hC K hK m hm hsq hE).mp (by omega)
    have h9 : m ∉ ({{{s9_txt}}} : Finset ℕ) := fun h9 => by
      have := (CN1.classNumber_eq_one_iff K hK m hm hsq).mpr h9
      omega
    simp only [Finset.mem_insert, Finset.mem_singleton] at h27 h9 ⊢
    omega
  · intro h18
    have h18' : m ∈ HCN.Finite.ClassTwo.classTwo18 := by
      rw [HCN.Finite.ClassTwo.classTwo18]
      simp only [Finset.mem_insert, Finset.mem_singleton] at h18 ⊢
      omega
    exact HCN.Finite.ClassTwo.classNumber_eq_two_of_mem hK hm hsq h18'

end HCN.Assembly
"""
open(f"{LEAN}/HCN/Assembly.lean", "w").write(asm)
print(f"wrote {LEAN}/HCN/Assembly.lean")

# ---- HCN/Main.lean (the two interfaces discharged by their proofs) ----
tmpl = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "Main.lean.in")).read()
tmpl = tmpl.replace("@S27@", s27_txt).replace("@S18@", s18_txt)
assert "@" not in tmpl.replace("@[", "")
open(f"{LEAN}/HCN/Main.lean", "w").write(tmpl)
print(f"wrote {LEAN}/HCN/Main.lean")
