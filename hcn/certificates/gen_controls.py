#!/usr/bin/env python3
"""Generates the tampered challenge statements under <out>/HCNNegControls/Tamper/ from the challenge file
<out>/HCNChallenges/ClassNumberLeTwo.lean (sets and statements are READ from it, never typed by hand). Comparator
against HCN.Main must reject each one ("do not match"):
  Tamper/Move163        163 moved from the nine into the class-number-two set (claims h(-163) = 2)
  Tamper/DropSquarefree the `Squarefree m` hypothesis dropped from both statements
  Tamper/Swap431        427 replaced by 431 in both sets (h(-431) = 21)
No HCN module imports HCNNegControls. Usage: python3 gen_controls.py <out>"""
import os, re, sys
L = sys.argv[1] if len(sys.argv) > 1 else "."
ch = open(f"{L}/HCNChallenges/ClassNumberLeTwo.lean").read()
i = ch.index("namespace HCN"); j = ch.index("end HCN")
body = ch[i:j + len("end HCN")]
lits = re.findall(r"\(\{([0-9, ]+)\} : Finset ℕ\)", body)
s27, s18 = lits
assert len(s27.split(",")) == 27 and len(s18.split(",")) == 18
def stmt(name):
    k = body.index("theorem " + name); e = body.index(":= by", k)
    return body[k:e].rstrip()
st_le, st_eq = stmt("classNumber_le_two_iff"), stmt("classNumber_eq_two_iff")
S9 = ", ".join(s27.split(", ")[:9]); assert S9 == "1, 2, 3, 7, 11, 19, 43, 67, 163"
os.makedirs(f"{L}/HCNNegControls/Tamper", exist_ok=True)
def write(rel, txt):
    open(f"{L}/HCNNegControls/{rel}", "w").write(txt); print("wrote", rel)
HDR = "import Mathlib\n\n"
def tamper(name, doc, newbody):
    assert newbody != body
    write(f"Tamper/{name}.lean", HDR + f"/-!\n# NEGATIVE CONTROL: tampered challenge `{name}`\n\n{doc}\n"
          "GENERATED by hcn/certificates/gen_controls.py from HCNChallenges/ClassNumberLeTwo.lean. A challenge-side module:\n"
          "imported by no solution module. Comparator against HCN.Main MUST fail (statement mismatch).\n-/\n\nopen NumberField\n\n" + newbody + "\n")
# (a) 163 moved into the 18-set
b = body.replace(f"({{{s18}}} : Finset ℕ)", f"({{{s18}, 163}} : Finset ℕ)"); assert b.count(", 163}") == 1
tamper("Move163", "163 is moved from the nine (class number one) into the eighteen: the second statement now claims h(-163) = 2.", b)
# (a') drop Squarefree
b = body.replace("(m : ℕ) (hm : Squarefree m) (hsq", "(m : ℕ) (hsq"); assert b.count("Squarefree") == body.count("Squarefree") - 2
tamper("DropSquarefree", "The hypothesis `Squarefree m` is dropped from both statements.", b)
# (a'') 427 -> 431
b = body.replace(", 427}", ", 431}"); assert b.count("431}") == 2
tamper("Swap431", "427 is replaced by 431 (h(-431) = 21) in both sets.", b)
